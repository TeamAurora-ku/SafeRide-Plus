class BinaryDrowsinessDataset(Dataset):

    def __init__(self, image_folder_dataset, selected_classes):

        self.dataset = image_folder_dataset
        self.selected_classes = selected_classes

        self.class_to_idx = {
            class_name: index
            for index, class_name in enumerate(selected_classes)
        }

        self.selected_indices = []

        for index, (_, label) in enumerate(self.dataset.samples):

            original_class = self.dataset.classes[label]

            if original_class in selected_classes:
                self.selected_indices.append(index)

    def __len__(self):
        return len(self.selected_indices)

    def __getitem__(self, index):

        original_index = self.selected_indices[index]

        image, original_label = self.dataset[original_index]

        original_class = self.dataset.classes[original_label]

        new_label = self.class_to_idx[original_class]

        return image, new_label


